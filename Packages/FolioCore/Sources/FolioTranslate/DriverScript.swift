async def _translate(settings, file):
    from pdf2zh_next.high_level import do_translate_async_stream

    finished = False
    try:
        async for event in do_translate_async_stream(settings, file):
            kind = event.get("type")
            if kind in ("progress_start", "progress_update", "progress_end"):
                emit({
                    "type": kind,
                    "stage": event.get("stage"),
                    "stage_current": event.get("stage_current"),
                    "stage_total": event.get("stage_total"),
                    "stage_progress": event.get("stage_progress"),
                    "overall_progress": event.get("overall_progress"),
                    "part_index": event.get("part_index"),
                    "total_parts": event.get("total_parts"),
                })
            elif kind == "finish":
                out = {"type": "finish"}
                out.update(_result_paths(event.get("translate_result")))
                out["token_usage"] = event.get("token_usage")
                emit(out)
                finished = True
                break
            elif kind == "error":
                emit({
                    "type": "error",
                    "error": str(event.get("error", "")),
                    "error_type": event.get("error_type"),
                    "details": _clip(event.get("details", "")),
                })
                return 1
    except Exception as e:  # noqa: BLE001
        import traceback

        emit({"type": "error", "error": str(e), "error_type": e.__class__.__name__, "details": _clip(traceback.format_exc())})
        return 1
    if not finished:
        emit({"type": "error", "error": "Translation ended without a result", "error_type": "NoResult", "details": ""})
        return 1
    return 0


